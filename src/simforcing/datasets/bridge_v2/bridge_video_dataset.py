def _distributed_barrier() -> None:
    """No-op barrier used to order stats writes before stats reads.

    On a shared / network filesystem (CephFS et al.) a freshly written
    ``dataset_stats.json`` is not guaranteed to be visible with its new
    content on OTHER nodes the instant the writer returns: they can still see
    the stale (or just-truncated, i.e. EMPTY) inode, which surfaces as
    ``json.JSONDecodeError: Expecting value: line 1 column 1``. Syncing the
    process group after the write makes every rank wait for the writer.
    """
    if torch.distributed.is_available() and torch.distributed.is_initialized():
        torch.distributed.barrier()


