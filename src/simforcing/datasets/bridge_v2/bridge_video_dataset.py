def _read_video_decord(path: str) -> torch.Tensor:
    """Read all frames from a video file as uint8 tensor [T, C, H, W]."""
    import decord  # local import; decord may not be installed in every env

    decord.bridge.set_bridge("torch")
    vr = decord.VideoReader(str(path), num_threads=1)
    frames = vr.get_batch(list(range(len(vr))))  # [T, H, W, C] uint8
    if not isinstance(frames, torch.Tensor):
        frames = torch.as_tensor(frames)
    if frames.dtype != torch.uint8:
        frames = frames.to(torch.uint8)
    frames = frames.permute(0, 3, 1, 2).contiguous()  # [T, C, H, W]
    return frames


def _probe_video_frames(path: str) -> int:
    """Return the number of frames in a video file (cheap; no full decode)."""
    import decord

    vr = decord.VideoReader(str(path), num_threads=1)
    return int(len(vr))


