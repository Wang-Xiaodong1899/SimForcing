"""BridgeData V2 video dataset for VideoActionModel.

This dataset loads (video, action, proprio) windows from the BridgeData V2
RLDS dataset, paired with simulator-rendered MP4 videos located on disk.

The MP4 files have been generated by
``simpler_env/utils/debug/widowx_test_dataset_inference_rollout_gt_traj_in_sim.py``
where each ``<episode_idx>.mp4`` corresponds to bridge train episode ``idx``,
and each frame is the horizontal concatenation of (sim render | gt image).
We only use the LEFT half of each frame.

The downstream sample format mirrors
``simforcing.datasets.prompts.RobotVideoDataset.__getitem__``
so existing VideoActionModel training pipelines can consume it without changes.

To use this dataset:

1. Run ``scripts/prepare_bridge_v2_meta.py`` once to materialize the
   per-episode actions / proprio / instruction caches and the
   ``meta/tasks.jsonl`` file required by ``precompute_text_embeds.py``.
2. Run ``scripts/precompute_text_embeds.py`` to generate the T5 text
   embedding cache.
3. Configure ``configs/data/bridge_real.yaml`` and start training.
"""

