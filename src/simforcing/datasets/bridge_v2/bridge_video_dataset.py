class _BridgeEpisodeIndex:
    """Reads per-episode metadata produced by ``prepare_bridge_v2_meta.py``.

    Layout (under ``dataset_dir``):

        meta/
            episodes.jsonl       # one record per episode
            tasks.jsonl          # unique tasks (for text-embed precompute)
        data/
            episode_<idx>.npz    # actions, states, instruction
        videos/                  # symlink or directory containing <idx>.mp4
                                 # (path can be overridden via `video_root`)

    ``episodes.jsonl`` records are dicts with at least:

        {"episode_index": int,
         "num_steps": int,
         "instruction": str,
         "task_index": int,
         "video_path": str}
    """

    def __init__(self, dataset_dir: str, video_root: Optional[str] = None):
        self.dataset_dir = Path(dataset_dir)
        self.meta_dir = self.dataset_dir / "meta"
        self.data_dir = self.dataset_dir / "data"
        self.video_root_override = Path(video_root) if video_root else None

        ep_jsonl = self.meta_dir / "episodes.jsonl"
        if not ep_jsonl.exists():
            raise FileNotFoundError(
                f"Missing {ep_jsonl}. Did you run scripts/prepare_bridge_v2_meta.py?"
            )

        self.episodes: List[Dict[str, Any]] = []
        with ep_jsonl.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                self.episodes.append(json.loads(line))

        # Verify every episode has a usable mp4, probe its real frame count,
        # and clamp ``num_steps`` to ``min(num_steps, video_frames)`` so that
        # mp4s that are shorter than the recorded number of steps don't
        # break window sampling at training time.
        # Frame counts are cached on disk so subsequent runs don't re-probe.
        frame_count_cache_path = self.meta_dir / "video_frame_counts.json"
        frame_count_cache: Dict[str, int] = {}
        if frame_count_cache_path.exists():
            try:
                with frame_count_cache_path.open("r", encoding="utf-8") as f:
                    frame_count_cache = json.load(f)
                if not isinstance(frame_count_cache, dict):
                    frame_count_cache = {}
            except Exception:
                frame_count_cache = {}

        kept: List[Dict[str, Any]] = []
        n_missing = 0
        n_shorter = 0
        cache_dirty = False
        for rec in self.episodes:
            vpath = self._resolve_video_path(rec)
            if not vpath.exists():
                n_missing += 1
                continue
            vpath_str = str(vpath)
            if vpath_str in frame_count_cache:
                vframes = int(frame_count_cache[vpath_str])
            else:
                try:
                    vframes = _probe_video_frames(vpath_str)
                except Exception as e:
                    logger.warning(
                        "BridgeV2: failed to probe %s: %s; skipping.", vpath_str, e
                    )
                    n_missing += 1
                    continue
                frame_count_cache[vpath_str] = vframes
                cache_dirty = True

            orig_num_steps = int(rec.get("num_steps", 0))
            effective = min(orig_num_steps, vframes)
            if vframes < orig_num_steps:
                n_shorter += 1
            rec["num_steps"] = int(effective)  # clamp in-place
            rec["_resolved_video_path"] = vpath_str
            kept.append(rec)

        if cache_dirty:
            try:
                self.meta_dir.mkdir(parents=True, exist_ok=True)
                with frame_count_cache_path.open("w", encoding="utf-8") as f:
                    json.dump(frame_count_cache, f)
            except Exception as e:
                logger.warning(
                    "BridgeV2: failed to write %s: %s", frame_count_cache_path, e
                )

        if n_missing > 0:
            logger.warning(
                "BridgeV2: %d/%d episodes have a usable mp4 file; the rest will be ignored.",
                len(kept),
                len(self.episodes),
            )
        if n_shorter > 0:
            logger.warning(
                "BridgeV2: %d episodes have an mp4 with fewer frames than their "
                "recorded num_steps; clamping num_steps = min(num_steps, video_frames).",
                n_shorter,
            )
        self.episodes = kept
        if not self.episodes:
            raise RuntimeError("BridgeV2: no usable episodes found.")

    def _resolve_video_path(self, rec: Dict[str, Any]) -> Path:
        if self.video_root_override is not None:
            return self.video_root_override / f"{rec['episode_index']}.mp4"
        return Path(rec["video_path"])

    def __len__(self):
        return len(self.episodes)

    def get_record(self, ep_local_idx: int) -> Dict[str, Any]:
        return self.episodes[ep_local_idx]

    def load_episode_arrays(self, ep_local_idx: int) -> Dict[str, np.ndarray]:
        rec = self.episodes[ep_local_idx]
        npz_path = self.data_dir / f"episode_{rec['episode_index']}.npz"
        if not npz_path.exists():
            raise FileNotFoundError(f"Missing {npz_path}")
        with np.load(npz_path, allow_pickle=False) as data:
            return {
                "action": data["action"].astype(np.float32),  # [N, 7]
                "state": data["state"].astype(np.float32),    # [N, 7]
            }


