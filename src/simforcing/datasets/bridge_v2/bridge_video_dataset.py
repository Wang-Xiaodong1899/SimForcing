class BridgeV2VideoDataset(torch.utils.data.Dataset):
    """BridgeData V2 video + 7-D action dataset.

    Each sample window has ``num_frames`` time steps. The video is
    sub-sampled at ``action_video_freq_ratio`` to produce
    ``T_video = (num_frames - 1) // action_video_freq_ratio + 1`` frames,
    and ``num_frames - 1`` actions / proprio are returned aligned with the
    video transitions. This matches the ``RobotVideoDataset`` convention.
    """

    def __init__(
        self,
        dataset_dirs: List[str],
        # shapes
        action_dim: int = 7,
        proprio_dim: int = 7,
        # window
        num_frames: int = 33,
        action_video_freq_ratio: int = 1,
        global_sample_stride: int = 1,
        # Each __getitem__ randomly picks a starting frame inside the chosen
        # episode. ``samples_per_episode`` controls how many sample slots each
        # episode contributes to ``__len__`` (i.e. the nominal epoch size is
        # ``num_episodes * samples_per_episode``). The actual starting frame
        # is re-randomized on every __getitem__ call.
        samples_per_episode: int = 1,
        # video
        video_size: List[int] = (240, 320),
        video_root: Optional[str] = None,
        use_left_half_only: bool = True,
        use_right_half_only: bool = False,
        # When True, the half (left=sim / right=real) is randomly chosen
        # PER-SAMPLE at __getitem__ time. This lets a single batch contain
        # both sim and real frames, which is useful for joint domain training.
        # Overrides `use_left_half_only` / `use_right_half_only` when set.
        random_half: bool = False,
        # Probability of picking the LEFT (sim) half when `random_half=True`.
        # Set to 0.5 for a balanced mix, <0.5 to bias toward real, etc.
        random_half_left_prob: float = 0.5,
        # When True, the dataset doubles its length: index `idx` (for
        # idx < base_len) returns the LEFT half (sim) and `idx + base_len`
        # returns the RIGHT half (real) of the SAME (episode, start_frame).
        # The (idx, idx + base_len) pair therefore shares identical action,
        # proprio, instruction and timing -- only the visual modality
        # differs. With a shuffling DataLoader, batches naturally interleave
        # sim and real samples; both halves of each pair are guaranteed to
        # appear in the same epoch, though not necessarily in the same batch.
        # Overrides `use_left_half_only` / `use_right_half_only` /
        # `random_half` when set.
        paired_halves: bool = False,
        # When True, build a "cross-domain" window whose FIRST frame comes
        # from the RIGHT half (real camera image) while ALL REMAINING frames
        # come from the LEFT half (sim render). This lets the model be
        # conditioned on a REAL first frame and asked to predict a SIM video
        # rollout. Overrides `use_left_half_only` / `use_right_half_only` /
        # `random_half` / `paired_halves` when set.
        first_frame_real_rest_sim: bool = False,
        # split
        val_set_proportion: float = 0.0,
        is_training_set: bool = True,
        seed: int = 42,
        # text
        text_embedding_cache_dir: Optional[str] = None,
        context_len: int = 128,
        # normalization
        norm_mode: str = "min/max",
        pretrained_norm_stats: Optional[str] = None,
        # debug
        override_instruction: Optional[str] = None,
        # `processor` is accepted for compatibility with model configs that
        # interpolate ${data.train.processor.action_output_dim} /
        # ${data.train.processor.proprio_output_dim}. The dataset itself does
        # NOT use it (action / proprio normalization is handled internally).
        processor: Optional[Any] = None,
    ):
        super().__init__()
        del processor  # unused
        if isinstance(dataset_dirs, (str, os.PathLike)):
            dataset_dirs = [str(dataset_dirs)]
        else:
            dataset_dirs = list(dataset_dirs)
        if len(dataset_dirs) == 0:
            raise ValueError("`dataset_dirs` must contain at least one entry.")

        self.dataset_dirs = dataset_dirs
        self.action_dim = int(action_dim)
        self.proprio_dim = int(proprio_dim)
        self.num_frames = int(num_frames)
        self.action_video_freq_ratio = int(action_video_freq_ratio)
        self.global_sample_stride = int(global_sample_stride)
        self.samples_per_episode = int(samples_per_episode)
        if self.samples_per_episode < 1:
            raise ValueError("`samples_per_episode` must be >= 1.")
        self.video_size = list(video_size)
        self.video_root = video_root
        self.use_left_half_only = bool(use_left_half_only)
        self.use_right_half_only = bool(use_right_half_only)
        self.random_half = bool(random_half)
        self.random_half_left_prob = float(random_half_left_prob)
        self.paired_halves = bool(paired_halves)
        self.first_frame_real_rest_sim = bool(first_frame_real_rest_sim)
        if self.random_half and not (0.0 <= self.random_half_left_prob <= 1.0):
            raise ValueError(
                f"random_half_left_prob must be in [0, 1], got {self.random_half_left_prob}"
            )
        if self.random_half and self.first_frame_real_rest_sim:
            # MIXED-TARGET mode: `random_half_left_prob` now selects between
            #   (real first frame -> SIM video)  [prob = random_half_left_prob]
            #   (real first frame -> REAL video) [prob = 1 - that]
            # per sample, so ONE training run sees both targets and the prompt
            # template (SIM_PROMPT / REAL_PROMPT) follows the target domain.
            logger.info(
                "BridgeV2VideoDataset: MIXED-TARGET mode "
                "(random_half + first_frame_real_rest_sim): p(sim target)=%.3f, "
                "p(real target)=%.3f. Both are conditioned on a REAL first frame.",
                self.random_half_left_prob,
                1.0 - self.random_half_left_prob,
            )
            if self.use_left_half_only or self.use_right_half_only or self.paired_halves:
                logger.warning(
                    "BridgeV2VideoDataset: MIXED-TARGET mode overrides "
                    "`use_left_half_only` / `use_right_half_only` / `paired_halves`."
                )
        elif self.first_frame_real_rest_sim and (
            self.use_left_half_only
            or self.use_right_half_only
            or self.paired_halves
        ):
            logger.warning(
                "BridgeV2VideoDataset: `first_frame_real_rest_sim=True` overrides "
                "`use_left_half_only` / `use_right_half_only` / `random_half` / "
                "`paired_halves`."
            )
        elif self.paired_halves and (
            self.use_left_half_only
            or self.use_right_half_only
            or self.random_half
        ):
            logger.warning(
                "BridgeV2VideoDataset: `paired_halves=True` overrides "
                "`use_left_half_only` / `use_right_half_only` / `random_half`."
            )
        elif self.random_half and (self.use_left_half_only or self.use_right_half_only):
            logger.warning(
                "BridgeV2VideoDataset: `random_half=True` overrides "
                "`use_left_half_only` / `use_right_half_only`."
            )
        self.val_set_proportion = float(val_set_proportion)
        self.is_training_set = bool(is_training_set)
        self.seed = int(seed)
        self.text_embedding_cache_dir = text_embedding_cache_dir
        self.context_len = int(context_len)
        self.norm_mode = norm_mode
        # An empty / whitespace-only override means "no override": fall back to
        # the per-episode instruction. This MUST match
        # `scripts/precompute_text_embeds.py::_get_override_prompts`, which
        # skips empty values and encodes the real per-task prompts instead.
        # Without this, every sample would be prompted with an EMPTY task
        # (e.g. SIM_PROMPT.format(task="")), whose embedding is never
        # precomputed -> FileNotFoundError at __getitem__ time.
        if isinstance(override_instruction, str) and override_instruction.strip() == "":
            override_instruction = None
        self.override_instruction = override_instruction

        # Sanity checks (mirror RobotVideoDataset constraints)
        assert (self.num_frames - 1) % self.action_video_freq_ratio == 0, (
            f"num_frames-1 must be divisible by action_video_freq_ratio, got "
            f"{self.num_frames - 1} and {self.action_video_freq_ratio}"
        )
        T_video = (self.num_frames - 1) // self.action_video_freq_ratio
        assert T_video % 4 == 0, (
            f"video frames (excluding init) must be divisible by 4 for "
            f"tokenization, got {T_video}"
        )
        # Sub-sample indices into the per-step time axis.
        self.video_sample_indices = list(
            range(0, self.num_frames, self.action_video_freq_ratio)
        )

        # Image post-processing pipeline.
        self.resize_transform = ResizeSmallestSideAspectPreserving(
            args={"img_w": self.video_size[1], "img_h": self.video_size[0]},
        )
        self.crop_transform = CenterCrop(
            args={"img_w": self.video_size[1], "img_h": self.video_size[0]},
        )
        self.normalize_transform = Normalize(
            args={"mean": 0.5, "std": 0.5},
        )

        # Build per-dataset_dir indices and concatenate.
        self._indices: List[_BridgeEpisodeIndex] = []
        for d in self.dataset_dirs:
            self._indices.append(_BridgeEpisodeIndex(d, video_root=self.video_root))

        # Episode-level train/val split (deterministic).
        self._episode_pool: List[tuple[int, int]] = []  # (idx_in_indices, ep_local_idx)
        for di, idx in enumerate(self._indices):
            n = len(idx)
            ep_indices = list(range(n))
            if self.val_set_proportion > 1e-6:
                rng = np.random.default_rng(self.seed + di)
                rng.shuffle(ep_indices)
                split_at = int(n * (1.0 - self.val_set_proportion))
                if self.is_training_set:
                    ep_indices = ep_indices[:split_at]
                else:
                    ep_indices = ep_indices[split_at:]
            self._episode_pool.extend((di, e) for e in ep_indices)

        # Filter out episodes that are too short to produce a full window.
        # We require ``num_steps >= num_frames`` so that
        # ``frames[start : start + num_frames]`` always returns exactly
        # ``num_frames`` frames without any padding.
        valid_pool: List[tuple[int, int]] = []
        n_dropped = 0
        for di, ep_local in self._episode_pool:
            rec = self._indices[di].get_record(ep_local)
            if int(rec["num_steps"]) >= self.num_frames:
                valid_pool.append((di, ep_local))
            else:
                n_dropped += 1
        if n_dropped > 0:
            logger.warning(
                "BridgeV2VideoDataset: dropped %d episodes with num_steps < %d.",
                n_dropped,
                self.num_frames,
            )
        self._episode_pool = valid_pool

        if not self._episode_pool:
            raise RuntimeError(
                f"BridgeV2VideoDataset: no episodes have at least num_frames={self.num_frames} "
                "steps; lower `num_frames`."
            )

        # Nominal epoch size = num_episodes * samples_per_episode.
        # __getitem__ maps idx -> episode via modulo and re-samples a random
        # start frame each time.
        self._epoch_size = len(self._episode_pool) * self.samples_per_episode

        logger.info(
            "BridgeV2VideoDataset(%s) initialized: %d episodes, "
            "samples_per_episode=%d, epoch_size=%d, num_frames=%d, "
            "action_video_freq_ratio=%d.",
            "train" if self.is_training_set else "val",
            len(self._episode_pool),
            self.samples_per_episode,
            self._epoch_size,
            self.num_frames,
            self.action_video_freq_ratio,
        )

        # Normalization stats.
        self._action_norm: Optional[SingleFieldLinearNormalizer] = None
        self._state_norm: Optional[SingleFieldLinearNormalizer] = None

        if pretrained_norm_stats:
            stats = load_dataset_stats_from_json(pretrained_norm_stats)
            logger.info(f"Using dataset stats: {pretrained_norm_stats}")
            if PartialState().is_main_process:
                work_dir = misc.get_work_dir()
                if work_dir is not None:
                    save_dataset_stats_to_json(
                        stats, os.path.join(work_dir, "dataset_stats.json")
                    )
            self._set_normalizers_from_stats(stats)
        else:
            if not self.is_training_set:
                raise ValueError(
                    "pretrained_norm_stats must be provided for validation/test sets."
                )
            if PartialState().is_main_process:
                logger.info("Computing BridgeV2 dataset stats for normalization...")
                stats = self._compute_dataset_stats()
                work_dir = misc.get_work_dir()
                if work_dir is not None:
                    save_dataset_stats_to_json(
                        stats, os.path.join(work_dir, "dataset_stats.json")
                    )
            else:
                stats = None
            # The val dataset (built right after this one) reads the file we
            # just wrote, from EVERY rank. Sync first, otherwise a rank on
            # another node can still see the truncated/empty inode.
            _distributed_barrier()
            if torch.distributed.is_available() and torch.distributed.is_initialized():
                obj_list = [stats]
                torch.distributed.broadcast_object_list(obj_list, src=0)
                stats = obj_list[0]
            self._set_normalizers_from_stats(stats)

    # ------------------------------------------------------------------ #
    # Stats / normalization                                              #
    # ------------------------------------------------------------------ #

    def _compute_dataset_stats(self) -> Dict[str, Any]:
        if not PartialState().is_main_process:
            return None  # other ranks will receive via broadcast

        action_mins, action_maxs = [], []
        action_sum, action_sumsq, action_cnt = 0.0, 0.0, 0
        action_q01, action_q99 = [], []
        state_mins, state_maxs = [], []
        state_sum, state_sumsq, state_cnt = 0.0, 0.0, 0
        state_q01, state_q99 = [], []

        for di, ep_local in self._episode_pool:
            arrs = self._indices[di].load_episode_arrays(ep_local)
            a = torch.from_numpy(arrs["action"]).float()  # [N, 7]
            s = torch.from_numpy(arrs["state"]).float()
            action_mins.append(a.amin(dim=0))
            action_maxs.append(a.amax(dim=0))
            action_sum = action_sum + a.sum(dim=0)
            action_sumsq = action_sumsq + (a * a).sum(dim=0)
            action_cnt += a.shape[0]
            action_q01.append(torch.quantile(a, 0.01, dim=0))
            action_q99.append(torch.quantile(a, 0.99, dim=0))

            state_mins.append(s.amin(dim=0))
            state_maxs.append(s.amax(dim=0))
            state_sum = state_sum + s.sum(dim=0)
            state_sumsq = state_sumsq + (s * s).sum(dim=0)
            state_cnt += s.shape[0]
            state_q01.append(torch.quantile(s, 0.01, dim=0))
            state_q99.append(torch.quantile(s, 0.99, dim=0))

        def _agg(mins, maxs, q01s, q99s, ssum, ssumsq, n):
            mn = torch.stack(mins).amin(dim=0)
            mx = torch.stack(maxs).amax(dim=0)
            q01 = torch.stack(q01s).amin(dim=0)
            q99 = torch.stack(q99s).amax(dim=0)
            mean = ssum / max(n, 1)
            var = ssumsq / max(n, 1) - mean * mean
            std = var.clamp_min(0.0).sqrt()
            return {
                "min": mn,
                "max": mx,
                "q01": q01,
                "q99": q99,
                "mean": mean,
                "std": std,
            }

        action_stats = _agg(action_mins, action_maxs, action_q01, action_q99,
                            action_sum, action_sumsq, action_cnt)
        state_stats = _agg(state_mins, state_maxs, state_q01, state_q99,
                           state_sum, state_sumsq, state_cnt)

        return {
            "action": {"default": action_stats},
            "state": {"default": state_stats},
            "num_episodes": len(self._episode_pool),
            "num_transition": action_cnt,
        }

    def _set_normalizers_from_stats(self, stats: Dict[str, Any]):
        a_stats = stats["action"]["default"]
        s_stats = stats["state"]["default"]
        # Convert lists -> tensors if needed (load_dataset_stats_from_json handles it,
        # but compute path emits tensors directly so this is a no-op there).

        def _to_tensor_dict(d):
            return {k: (v if isinstance(v, torch.Tensor) else torch.as_tensor(v).float())
                    for k, v in d.items()}

        self._action_norm = SingleFieldLinearNormalizer(
            stats=_to_tensor_dict(a_stats), mode=self.norm_mode
        )
        self._state_norm = SingleFieldLinearNormalizer(
            stats=_to_tensor_dict(s_stats), mode=self.norm_mode
        )

    # ------------------------------------------------------------------ #
    # Length / item                                                      #
    # ------------------------------------------------------------------ #

    def __len__(self) -> int:
        # When `paired_halves=True`, each underlying (episode, start) is
        # exposed as TWO samples (left & right half), doubling the length.
        return self._epoch_size * (2 if self.paired_halves else 1)

    # ------------------------------------------------------------------ #
    # Window construction                                                #
    # ------------------------------------------------------------------ #

    def _load_window(
        self,
        di: int,
        ep_local: int,
        start: int,
        half: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Load a fixed-size window starting at ``start`` from one episode.

        Pre-condition: ``start + num_frames <= num_steps`` (guaranteed by
        ``_get`` because ``_episode_pool`` is filtered to only include
        episodes with ``num_steps >= num_frames``).
        """
        rec = self._indices[di].get_record(ep_local)
        num_steps = int(rec["num_steps"])
        T = self.num_frames
        if start < 0 or start + T > num_steps:
            raise ValueError(
                f"Invalid window start={start}, num_steps={num_steps}, T={T}."
            )

        arrs = self._indices[di].load_episode_arrays(ep_local)
        action_full = torch.from_numpy(arrs["action"]).float()  # [N, 7]
        state_full = torch.from_numpy(arrs["state"]).float()    # [N, 7]
        instruction = rec["instruction"]
        video_path = rec["_resolved_video_path"]

        # ---- Video frames (always exactly T frames, no padding) ---- #
        try:
            full_video = _read_video_decord(video_path)  # [F, C, H, W] uint8
        except Exception as e:
            raise RuntimeError(f"Failed to read {video_path}: {e}") from e
        # Decide which half to keep.
        if half is None:
            if self.random_half:
                pick_sim_target = np.random.rand() < self.random_half_left_prob
                if not pick_sim_target:
                    half = "right"
                elif self.first_frame_real_rest_sim:
                    # MIXED-TARGET mode: sim target, but still grounded on a
                    # REAL first frame -- so this run mixes
                    # (real image -> sim video) and (real image -> real video).
                    half = "first_real_rest_sim"
                else:
                    half = "left"
            elif self.first_frame_real_rest_sim:
                half = "first_real_rest_sim"
            elif self.use_left_half_only:
                half = "left"
            elif self.use_right_half_only:
                half = "right"
            else:
                half = "full"
        if half == "left":
            W = full_video.shape[-1]
            full_video = full_video[..., : W // 2]
        elif half == "right":
            W = full_video.shape[-1]
            full_video = full_video[..., W // 2 :]
        elif half == "first_real_rest_sim":
            # Cross-domain window: frame 0 from the RIGHT half (real camera
            # image) used as the first-frame grounding condition, and ALL
            # remaining frames from the LEFT half (sim render) as the video
            # to predict. We slice the raw per-step frames here (before the
            # window / sub-sample step below) so that indices stay aligned.
            W = full_video.shape[-1]
            left = full_video[..., : W // 2]   # sim
            right = full_video[..., W // 2 :]  # real
            # Build a video whose frame 0 is real and frames 1.. are sim.
            full_video = left.clone()
            full_video[start : start + 1] = right[start : start + 1]
        elif half == "full":
            pass
        else:
            raise ValueError(
                f"Unknown half '{half}', expected "
                f"'left'/'right'/'first_real_rest_sim'/'full'."
            )
        if full_video.shape[0] < num_steps:
            # ``num_steps`` is already clamped to min(orig_num_steps, video_frames)
            # at __init__ time using a cached frame-count probe. If we still
            # land here, the cache is stale (mp4 was rewritten) -- ask the
            # user to refresh it.
            raise RuntimeError(
                f"Video {video_path} has {full_video.shape[0]} frames but "
                f"num_steps={num_steps}; cache may be stale. "
                f"Delete <dataset_dir>/meta/video_frame_counts.json and retry."
            )
        per_step_video = full_video[start : start + T]  # [T, C, H, W]

        # Sub-sample along the per-step time axis (no-op when ratio == 1).
        T_video_indices = torch.tensor(self.video_sample_indices, dtype=torch.long)
        video = per_step_video[T_video_indices]          # [T_video, C, H, W]

        # Resize / center-crop / normalize -> [-1, 1]
        video = self.resize_transform(video)
        video = self.crop_transform(video)
        video = self.normalize_transform(video)          # float, [-1, 1]
        video = video.permute(1, 0, 2, 3).contiguous()   # [C, T_video, H, W]

        # ---- Action / proprio extraction & normalization ---- #
        # Window has T per-step states and T-1 actions (one per transition).
        action = action_full[start : start + (T - 1)].clone()   # [T-1, 7]
        proprio = state_full[start : start + T].clone()         # [T,   7]

        if self._action_norm is not None:
            action = self._action_norm.forward(action)
        if self._state_norm is not None:
            proprio = self._state_norm.forward(proprio)

        # Match RobotVideoDataset: proprio aligned with action -> drop last.
        proprio_window = proprio[:-1, :]                  # [T-1, 7]

        # Padding masks are all-False since we never pad.
        zero_pad_action = torch.zeros(T - 1, dtype=torch.bool)
        zero_pad_image = torch.zeros(video.shape[1], dtype=torch.bool)

        # Sanity checks (mirror RobotVideoDataset).
        if video.shape[1] <= 1:
            raise ValueError(
                f"`video` must have at least 2 frames, got shape {tuple(video.shape)}"
            )
        if action.shape[0] % (video.shape[1] - 1) != 0:
            raise ValueError(
                f"`action` horizon ({action.shape[0]}) must be divisible by "
                f"`video` transitions ({video.shape[1] - 1})."
            )

        # ---- Instruction / text embedding ---- #
        if self.override_instruction is not None:
            instruction = self.override_instruction
        # Template is chosen by the domain of the TARGET video (`half`), so a
        # sim rollout gets SIM_PROMPT and a real rollout gets REAL_PROMPT even
        # when both are conditioned on the same real first frame.
        prompt = build_prompt(instruction, half=half)
        context, context_mask = self._get_cached_text_context(prompt)
        # Match wan2.2 behavior: zero out invalid positions, mask all True.
        context[~context_mask] = 0.0
        context_mask = torch.ones_like(context_mask)

        return {
            "video": video,
            "action": action,
            "proprio": proprio_window,
            "prompt": prompt,
            "context": context,
            "context_mask": context_mask,
            "image_is_pad": zero_pad_image,
            "action_is_pad": zero_pad_action,
            "proprio_is_pad": zero_pad_action.clone(),
            # Which half of the source mp4 was used for this sample.
            # 'left' = sim, 'right' = real, 'full' = no crop. Useful for
            # batch-level analysis when `random_half=True`.
            "half": half,
        }

    # ------------------------------------------------------------------ #
    # Text embedding cache lookup                                        #
    # ------------------------------------------------------------------ #

    def _get_cached_text_context(self, prompt: str):
        if self.text_embedding_cache_dir is None:
            raise ValueError("text_embedding_cache_dir is not set.")
        cache_dir = self.text_embedding_cache_dir
        os.makedirs(cache_dir, exist_ok=True)
        hashed = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
        cache_path = os.path.join(
            cache_dir, f"{hashed}.t5_len{self.context_len}.wan22ti2v5b.pt"
        )
        if not os.path.exists(cache_path):
            raise FileNotFoundError(
                f"Missing text embedding cache: {cache_path}. "
                "Run scripts/precompute_text_embeds.py first."
            )
        payload = torch.load(cache_path, map_location="cpu")
        context = payload["context"]
        context_mask = payload["mask"].bool()
        if context.ndim != 2:
            raise ValueError(
                f"Cached `context` must be 2D [L, D], got shape {tuple(context.shape)} "
                f"in {cache_path}"
            )
        if context_mask.ndim != 1:
            raise ValueError(
                f"Cached `mask` must be 1D [L], got shape {tuple(context_mask.shape)} "
                f"in {cache_path}"
            )
        if context.shape[0] != self.context_len:
            raise ValueError(
                f"Cached context_len mismatch: expected {self.context_len}, got "
                f"{context.shape[0]} in {cache_path}"
            )
        if context_mask.shape[0] != self.context_len:
            raise ValueError(
                f"Cached mask_len mismatch: expected {self.context_len}, got "
                f"{context_mask.shape[0]} in {cache_path}"
            )
        return context, context_mask

    # ------------------------------------------------------------------ #
    # __getitem__                                                        #
    # ------------------------------------------------------------------ #

    def _get(self, idx: int) -> Dict[str, Any]:
        # Map flat idx -> episode (deterministic) and pick a start frame
        # inside that episode. Episodes are pre-filtered so that
        # num_steps >= num_frames, hence the window is always full-length.
        if self.paired_halves:
            # Two "virtual" indices share the same (episode, start_frame):
            #   base_idx       -> LEFT  half (sim)
            #   base_idx + N   -> RIGHT half (real)
            base_idx = idx % self._epoch_size
            half = "left" if idx < self._epoch_size else "right"
            ep_idx = base_idx % len(self._episode_pool)
            di, ep_local = self._episode_pool[ep_idx]
            num_steps = int(self._indices[di].get_record(ep_local)["num_steps"])
            max_start = num_steps - self.num_frames
            # Deterministic, paired start frame: the two indices that point
            # to the same underlying clip MUST pick the same start. Seed by
            # the shared base_idx (plus the dataset seed for reproducibility).
            rng = np.random.default_rng(self.seed + 1_000_003 * base_idx)
            start = int(rng.integers(0, max_start + 1))
            return self._load_window(di, ep_local, start, half=half)

        ep_idx = idx % len(self._episode_pool)
        di, ep_local = self._episode_pool[ep_idx]
        num_steps = int(self._indices[di].get_record(ep_local)["num_steps"])
        # max valid start s.t. [start, start + num_frames) <= num_steps.
        max_start = num_steps - self.num_frames  # >= 0 by construction
        start = int(np.random.randint(0, max_start + 1))
        return self._load_window(di, ep_local, start)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        try:
            return self._get(idx)
        except Exception as e:
            print(f"Error processing sample idx {idx}: {e}. Returning a random sample instead.")
            print(traceback.format_exc())
            random_idx = int(np.random.randint(len(self)))
            return self._get(random_idx)
